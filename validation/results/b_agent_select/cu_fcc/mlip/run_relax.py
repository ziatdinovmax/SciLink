"""
ASE+mace RELAX script -- generated by SciLink.

Potential: mace-mp-0 (backend: mace)
Elements:  ['Cu']
Task:      relax

Run:
    python run_relax.py                          # uses default device
    MACE_DEVICE=cpu python run_relax.py    # force CPU
"""
import os
import time

from ase import units
from ase.io.lammpsdata import read_lammps_data
from mace.calculators import mace_mp

ELEMENTS = ['Cu']
DEVICE = os.environ.get('MACE_DEVICE', 'cuda')


def _load_structure():
    atoms = read_lammps_data('/qfs/people/alle927/SciLink/SciLink/validation/results/b_agent_select/cu_fcc/mlip/system.data', atom_style="atomic", sort_by_id=True)
    if ELEMENTS:
        # write_lammps_data(masses=True) lets ASE infer real elements from
        # masses on read, so atoms.numbers are true Zs in the typical case.
        # Only fall back to type-index remap if mass-based inference didn't
        # recover the expected element set.
        actual = sorted(set(atoms.get_chemical_symbols()))
        expected = sorted(set(ELEMENTS))
        if actual != expected:
            type_to_sym = {i + 1: ELEMENTS[i] for i in range(len(ELEMENTS))}
            nums = atoms.get_atomic_numbers()
            atoms.set_chemical_symbols([type_to_sym[int(n)] for n in nums])
    return atoms


def main():
    import json
    import numpy as np
    from ase.optimize import BFGS
    from ase.filters import FrechetCellFilter
    from ase.io import write

    atoms = _load_structure()
    print(f"system:  {len(atoms)} atoms "
          f"({sorted(set(atoms.get_chemical_symbols()))})")
    print(f"device:  {DEVICE}")
    atoms.calc = mace_mp(model='medium', device=DEVICE, default_dtype='float64')

    cell0 = atoms.cell.cellpar()
    print(f"initial cellpar: {np.round(cell0, 4)}")

    # FrechetCellFilter relaxes atomic positions AND the cell, so the
    # equilibrium lattice constant falls out of the optimization.
    opt = BFGS(FrechetCellFilter(atoms), logfile="relax.log")
    t0 = time.time()
    converged = opt.run(fmax=0.02, steps=500)
    elapsed = time.time() - t0

    cell1 = atoms.cell.cellpar()
    write("relaxed.xyz", atoms)

    result = {
        "converged": bool(converged),
        "steps": int(opt.nsteps),
        "fmax_threshold": 0.02,
        "final_energy_eV": float(atoms.get_potential_energy()),
        "initial_cellpar": [float(x) for x in cell0],
        "final_cellpar": [float(x) for x in cell1],
        "lattice_constant_A": float(cell1[0]),
        "elapsed_s": round(elapsed, 2),
    }
    with open("relax_result.json", "w") as f:
        json.dump(result, f, indent=2)

    print(f"final cellpar:   {np.round(cell1, 4)}")
    print(f"lattice constant: {cell1[0]:.4f} A")
    print(f"converged: {converged}  ({opt.nsteps} steps, {elapsed:.1f}s)")


if __name__ == "__main__":
    main()
