"""_generate_mlip_inputs must normalize to script CONTENTS, not a path.

The classical MD branch stores `Path(script).read_text()` in input_files; the
MLIP branch used to store the path STRING. The execution path writes each
input_files value verbatim into the run script, so a path string there becomes
the script body and the ASE run never executes. This checks the MLIP branch now
carries the source text, and that _collect_phases propagates it
(MLIP-execution-in-loop, Blocker 1).
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from scilink.agents.sim_agents import mlip_agent  # noqa: E402
from scilink.agents.sim_agents.simulation_pipeline import (  # noqa: E402
    _collect_phases,
    _generate_mlip_inputs,
)

_SCRIPT_SRC = (
    '"""ASE+mace MD script -- generated by SciLink."""\n'
    "import os\n"
    "from ase import units\n\n\n"
    "def main():\n"
    "    print('run')\n\n\n"
    "if __name__ == '__main__':\n"
    "    main()\n"
)


class _FakeMLIPAgent:
    """Stand-in for MLIPAgent: no credentials, writes a real driver script."""

    def __init__(self, working_dir, **kw):
        self.working_dir = working_dir

    def deploy_pretrained(self, **kw):
        p = Path(self.working_dir) / "run_md.py"
        p.write_text(_SCRIPT_SRC)
        # mirror the real return shape: run_path + runner + task
        return {"run_path": str(p), "runner": "ase", "task": "md"}


def test_mlip_input_files_carry_source_text_not_path(tmp_path, monkeypatch):
    monkeypatch.setattr(mlip_agent, "MLIPAgent", _FakeMLIPAgent)

    result = _generate_mlip_inputs(
        backend=None, structure_file="/nonexistent/structure.cif",
        request="MD of Pt bulk", output_dir=str(tmp_path),
        api_key=None, base_url=None, model_name="m",
    )

    files = result["input_files"]
    assert "run_md.py" in files
    body = files["run_md.py"]
    # the SOURCE TEXT, not the path string
    assert "import" in body and "def main" in body
    assert body == _SCRIPT_SRC
    assert body != str(tmp_path / "run_md.py")
    assert not body.strip().startswith("/")        # not a path
    assert result["entry_file"] == "run_md.py"
    assert result.get("runner") == "ase"


def test_collect_phases_carries_the_contents(tmp_path, monkeypatch):
    monkeypatch.setattr(mlip_agent, "MLIPAgent", _FakeMLIPAgent)
    result = _generate_mlip_inputs(
        backend=None, structure_file="/nonexistent/structure.cif",
        request="MD of Pt bulk", output_dir=str(tmp_path),
        api_key=None, base_url=None, model_name="m",
    )
    phases = _collect_phases(result, str(tmp_path), "python {script}")
    assert len(phases) == 1
    ph = phases[0]
    assert ph.entry_file == "run_md.py"
    assert "import" in ph.input_files["run_md.py"]
    assert ph.run_command == "python run_md.py"
